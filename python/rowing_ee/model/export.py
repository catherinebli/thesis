"""Generate firmware/include/PipelineConfig.h and ModelWeights.h.

Doubles are written with repr(), the shortest string that round-trips exactly,
so the firmware gets bit-identical constants.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

from ..config import PipelineConfig
from .linear_model import LinearModel

BANNER = "// AUTO-GENERATED by scripts/gen_headers.py from config/pipeline.yaml. Do not edit.\n"


def _f(v: float) -> str:
    s = repr(float(v))
    if s in ("inf", "-inf", "nan"):
        raise ValueError("non-finite constant")
    return s


def config_header_text(cfg: PipelineConfig) -> str:
    sos = cfg.sos()
    lines = [BANNER, "#pragma once", "#include <stdint.h>", ""]
    d = {
        "PC_FEATURE_HASH": f"0x{cfg.feature_hash():08X}u",
        "PC_FS_HZ": cfg.fs,
        "PC_N_IMU": cfg.n_imu,
        "PC_N_CH": cfg.n_ch,
        "PC_BINS": cfg.bins,
        "PC_D": cfg.D,
        "PC_N_SOS": sos.shape[0],
        "PC_STILL_N": cfg.still_n,
        "PC_MIN_STROKE_N": cfg.min_stroke_n,
        "PC_MAX_STROKE_N": cfg.max_stroke_n,
        "PC_REST_TIMEOUT_N": cfg.rest_timeout_n,
        "PC_RING_CAP": cfg.ring_capacity,
        "PC_DETECT_CH": cfg.detect_channel,
        "PC_DETECT_SIGN": cfg.detect_sign,
        "PC_I2C_HZ": f"{cfg.i2c_hz}u",
        "PC_ICM_ACCEL_FS_SEL": {2: 0, 4: 1, 8: 2, 16: 3}[cfg.accel_fs_g],
        "PC_ICM_GYRO_FS_SEL": {250: 0, 500: 1, 1000: 2, 2000: 3}[cfg.gyro_fs_dps],
        "PC_ICM_DLPF_CFG": cfg.dlpf_cfg,
        "PC_ICM_ODR_DIV": cfg.odr_div,
    }
    w = max(len(k) for k in d)
    lines += [f"#define {k:<{w}} {v}" for k, v in d.items()]
    lines.append("")
    consts = {
        "PC_ACCEL_SCALE": (cfg.accel_scale, "m/s^2 per count"),
        "PC_GYRO_SCALE": (cfg.gyro_scale, "rad/s per count"),
        "PC_MAX_STILL_GYRO_STD": (cfg.max_still_gyro_std, "rad/s"),
        "PC_THR_MIN": (cfg.thr_min, "rad/s"),
        "PC_THR_FRAC": (cfg.thr_frac, ""),
        "PC_HYST": (cfg.hyst, ""),
        "PC_MAX_ERR_FRAC": (cfg.max_err_frac, ""),
        "PC_K_REST": (cfg.k_rest, ""),
        "PC_P_MAX_W": (cfg.p_max_w, "W"),
    }
    for k, (v, unit) in consts.items():
        lines.append(f"static const double {k} = {_f(v)};" + (f"  // {unit}" if unit else ""))
    lines.append("")
    lines.append("// Butterworth low-pass, rows {b0, b1, b2, a0, a1, a2} (scipy sos layout)")
    lines.append("static const double PC_SOS[PC_N_SOS][6] = {")
    for row in sos:
        lines.append("    {" + ", ".join(_f(v) for v in row) + "},")
    lines.append("};")
    lines.append("")
    lines.append("// sensor -> segment frame, per IMU (signed permutation, det +1)")
    lines.append("static const int8_t PC_MOUNT[PC_N_IMU][3][3] = {")
    for k, imu in enumerate(cfg.imus):
        m = cfg.mount[k]
        rows = ", ".join("{" + ", ".join(str(int(v)) for v in r) + "}" for r in m)
        lines.append(f"    {{{rows}}},  // {imu.name}")
    lines.append("};")
    lines.append("")
    lines.append("struct PcImuSpec { const char* name; uint8_t bus; uint8_t mux; uint8_t channel; uint8_t addr; };")
    lines.append("// mux = 0 means the IMU is wired straight to the bus")
    lines.append("static const PcImuSpec PC_IMUS[PC_N_IMU] = {")
    for imu in cfg.imus:
        mux = 0 if imu.mux is None else imu.mux
        lines.append(f'    {{"{imu.name}", {imu.bus}, 0x{mux:02X}, {imu.channel}, 0x{imu.addr:02X}}},')
    lines.append("};")
    lines.append("")
    lines.append("static const char* const PC_CHANNEL_NAMES[PC_N_CH] = {")
    for i in range(0, cfg.n_ch, 6):
        lines.append("    " + ", ".join(f'"{n}"' for n in cfg.channel_names[i:i + 6]) + ",")
    lines.append("};")
    lines.append("")
    sd = cfg.subject_defaults
    lines.append(f'#define PC_SUBJ_ID "{str(sd["id"])[:15]}"')
    lines.append(f"static const double PC_SUBJ_MASS_KG = {_f(sd['mass_kg'])};")
    lines.append(f"static const double PC_SUBJ_HEIGHT_M = {_f(sd['height_m'])};")
    lines.append(f"static const double PC_SUBJ_AGE = {_f(sd['age'])};")
    lines.append(f"#define PC_SUBJ_SEX '{str(sd['sex'])[:1].upper()}'")
    lines.append("")
    return "\n".join(lines)


def weights_header_text(model: LinearModel, cfg: PipelineConfig) -> str:
    if model.D != cfg.D:
        raise ValueError(f"model has {model.D} weights, config expects D = {cfg.D}")
    fh = cfg.feature_hash() if model.feature_hash is None else model.feature_hash
    lines = [BANNER.replace("config/pipeline.yaml", "the trained model"), "#pragma once", ""]
    lines.append(f"#define MW_D {model.D}")
    lines.append(f"#define MW_FEATURE_HASH 0x{fh:08X}u")
    lines.append(f"#define MW_IS_PLACEHOLDER {1 if model.placeholder else 0}")
    lines.append("")
    lines.append("// w[0] is the intercept; normalization is already folded in (raw SI features)")
    lines.append("static const double MW_W[MW_D] = {")
    for i in range(0, model.D, 8):
        lines.append("    " + ", ".join(_f(v) for v in model.w[i:i + 8]) + ",")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def write_config_header(cfg: PipelineConfig, path: Path | str) -> None:
    Path(path).write_text(config_header_text(cfg), encoding="utf-8")


def write_weights_header(model: LinearModel, cfg: PipelineConfig, path: Path | str) -> None:
    Path(path).write_text(weights_header_text(model, cfg), encoding="utf-8")


def placeholder_model(cfg: PipelineConfig) -> LinearModel:
    return LinearModel(np.zeros(cfg.D), placeholder=True, feature_hash=cfg.feature_hash())
